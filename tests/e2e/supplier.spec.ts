import { expect, test, type ConsoleMessage, type Page } from '@playwright/test'

const supplierUrl = 'http://127.0.0.1:5178/'

function trackPageErrors(page: Page) {
  const errors: string[] = []
  const onConsole = (message: ConsoleMessage) => {
    const location = message.location().url || ''
    const infrastructureMapError = message.type() === 'error' && /status of 502/.test(message.text()) && /\/api\/tencent-map\//.test(location)
    const softwareWebglWarning = message.type() === 'warning' && (message.text().includes('WebGL') || message.text().includes('GroupMarkerNotSet'))
    if (!infrastructureMapError && !softwareWebglWarning && (message.type() === 'error' || message.type() === 'warning')) errors.push(`console.${message.type()}: ${message.text()}`)
  }
  const onPageError = (error: Error) => errors.push(`pageerror: ${error.message}`)
  page.on('console', onConsole)
  page.on('pageerror', onPageError)
  return {
    assertClean: () => expect(errors, errors.join('\n')).toEqual([]),
    dispose: () => {
      page.off('console', onConsole)
      page.off('pageerror', onPageError)
    }
  }
}

async function assertNoHorizontalOverflow(page: Page) {
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
}

async function login(page: Page, role: 'supplier' | 'driver') {
  await page.locator('.role-tabs uni-button').filter({ hasText: role === 'driver' ? '司机' : '供应商' }).click()
  await page.locator('.login-button').click()
  await expect(page.locator('.app-shell')).toBeVisible()
}

